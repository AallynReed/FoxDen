/// Canonical Huffman codes `(code, length)` for each symbol.
fn codes(t: &([u8; 16], &[u8])) -> [(u32, u32); 256] {
    let mut out = [(0, 0); 256];
    let (mut code, mut k) = (0u32, 0usize);
    for (i, &n) in t.0.iter().enumerate() {
        for _ in 0..n {
            out[t.1[k] as usize] = (code, i as u32 + 1);
            code += 1;
            k += 1;
        }
        code <<= 1;
    }
    out
}

#[derive(Default)]
struct Bits {
    out: Vec<u8>,
    acc: u8,
    n: u32,
}

impl Bits {
    fn put(&mut self, code: u32, len: u32) {
        for i in (0..len).rev() {
            self.acc = (self.acc << 1) | ((code >> i) & 1) as u8;
            self.n += 1;
            if self.n == 8 {
                self.out.push(self.acc);
                if self.acc == 0xFF {
                    self.out.push(0);
                }
                self.acc = 0;
                self.n = 0;
            }
        }
    }
    fn finish(mut self) -> Vec<u8> {
        while self.n != 0 {
            self.put(1, 1);
        }
        self.out
    }
}

fn segment(out: &mut Vec<u8>, marker: u8, body: &[u8]) {
    out.extend_from_slice(&[0xFF, marker]);
    out.extend_from_slice(&((body.len() + 2) as u16).to_be_bytes());
    out.extend_from_slice(body);
}

/// A `w` x `h` image filled with one colour.
pub fn solid(w: u16, h: u16, r: u8, g: u8, b: u8) -> Vec<u8> {
    let (r, g, b) = (r as f32, g as f32, b as f32);
    let ycc = [
        0.299 * r + 0.587 * g + 0.114 * b,
        -0.168_736 * r - 0.331_264 * g + 0.5 * b + 128.0,
        0.5 * r - 0.418_688 * g - 0.081_312 * b + 128.0,
    ];
    // with a quantiser of 1, a flat block's DC coefficient is 8 x (value - 128)
    let dc = ycc.map(|v| ((v - 128.0) * 8.0).round() as i32);
    let mut out = vec![0xFF, 0xD8];
    segment(&mut out, 0xE0, b"JFIF\0\x01\x01\0\0\x01\0\x01\0\0");
    let mut dqt = vec![0u8];
    dqt.extend_from_slice(&[1; 64]);
    segment(&mut out, 0xDB, &dqt);
    let [hh, hl] = h.to_be_bytes();
    let [wh, wl] = w.to_be_bytes();
    segment(
        &mut out,
        0xC0,
        &[8, hh, hl, wh, wl, 3, 1, 0x11, 0, 2, 0x11, 0, 3, 0x11, 0],
    );
    let mut dht = Vec::new();
    for (class, t) in [
        (0x00, &DC_LUM),
        (0x10, &AC_LUM),
        (0x01, &DC_CHR),
        (0x11, &AC_CHR),
    ] {
        dht.push(class);
        dht.extend_from_slice(&t.0);
        dht.extend_from_slice(t.1);
    }
    segment(&mut out, 0xC4, &dht);
    segment(&mut out, 0xDA, &[3, 1, 0x00, 2, 0x11, 3, 0x11, 0, 63, 0]);
    let dc_codes = [codes(&DC_LUM), codes(&DC_CHR)];
    let ac_codes = [codes(&AC_LUM), codes(&AC_CHR)];
    let blocks = w.div_ceil(8) as usize * h.div_ceil(8) as usize;
    let mut bits = Bits::default();
    let mut prev = [0i32; 3];
    for _ in 0..blocks {
        for c in 0..3 {
            let t = (c != 0) as usize;
            let diff = dc[c] - prev[c];
            prev[c] = dc[c];
            let cat = 32 - diff.unsigned_abs().leading_zeros();
            let (code, len) = dc_codes[t][cat as usize];
            bits.put(code, len);
            if cat > 0 {
                let v = if diff < 0 {
                    diff + (1 << cat) - 1
                } else {
                    diff
                };
                bits.put(v as u32, cat);
            }
            let (eob, len) = ac_codes[t][0];
            bits.put(eob, len);
        }
    }
    out.extend(bits.finish());
    out.extend_from_slice(&[0xFF, 0xD9]);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn standard_codes() {
        let dc = codes(&DC_LUM);
        assert_eq!(dc[0], (0b00, 2));
        assert_eq!(dc[6], (0b1110, 4));
        assert_eq!(dc[11], (0b1_1111_1110, 9));
        assert_eq!(codes(&AC_LUM)[0], (0b1010, 4));
        assert_eq!(codes(&AC_CHR)[0], (0b00, 2));
        assert_eq!(codes(&DC_CHR)[11], (0b111_1111_1110, 11));
    }

    #[test]
    fn small_enough_for_one_report() {
        for (w, c) in [(72, [0, 0, 0]), (96, [255, 255, 255]), (96, [255, 0, 128])] {
            let j = solid(w, w, c[0], c[1], c[2]);
            assert_eq!(j[..2], [0xFF, 0xD8]);
            assert_eq!(j[j.len() - 2..], [0xFF, 0xD9]);
            assert!(j.len() <= 1016, "{} bytes", j.len());
        }
    }
}
