/// ViaSendCommand(Sub): the reply must echo `head` and carry data after it.
fn query(io: &mut dyn Io, head: &[u8], args: &[u8]) -> Option<([u8; LEN], usize)> {
    let (b, n) = send(io, head, args).ok()?;
    (b[..head.len()] == *head && n > head.len()).then(|| (b, n - head.len()))
}

/// The constructor's queries: wireless PID, feature gate, LED count, LED index by matrix row, patches.
fn probe(io: &mut dyn Io, mut pid: u16) -> Option<Vec<Option<(u8, u8)>>> {
    if let Some((b, _)) = query(io, &[0xB2], &[]) {
        let (vid, p) = (
            u16::from_le_bytes([b[2], b[3]]),
            u16::from_le_bytes([b[4], b[5]]),
        );
        if b[1] == 0x01 && vid != 0 && p != 0 {
            pid = p;
        }
    }
    let features = match query(io, &[0xA2], &[]) {
        Some((b, _)) if b[1] == 0 => u16::from_le_bytes([b[2], b[3]]),
        Some((b, _)) => u16::from_le_bytes([b[1], b[2]]),
        None => 0,
    };
    let rgb = query(io, &[0xA8, 0x01], &[]).is_some_and(|(b, _)| b[2] | b[3] != 0);
    if features & 0x80 == 0 && !rgb {
        return None;
    }
    let n = query(io, &[0xA8, 0x05], &[]).map_or(0, |(b, _)| u16::from_be_bytes([b[2], b[3]]));
    let mut at = vec![None; n as usize];
    for row in 0..32u8 {
        let Some((b, k)) = query(io, &[0xA8, 0x06], &[row, 0xFF, 0xFF, 0xFF]) else {
            continue;
        };
        for (col, &led) in b[3..2 + k].iter().enumerate().filter(|p| *p.1 != 0xFF) {
            if let Some(slot @ None) = at.get_mut(led as usize) {
                *slot = Some((row, col as u8));
            }
        }
    }
    let raw = at.clone();
    if let Some((_, fix)) = PATCHES.iter().find(|(pids, _)| pids.contains(&pid)) {
        for e in fix.chunks_exact(4) {
            if let Some(i) = raw.iter().position(|p| *p == Some((e[0], e[1]))) {
                at[i] = Some((e[2], e[3]));
            }
        }
    }
    (!at.is_empty()).then_some(at)
}

struct Keychron;

impl Proto for Keychron {
    fn start(&mut self, io: &mut dyn Io) -> Result<(), String> {
        send(io, &[0x07], &[3, 2, 23])?;
        send(io, &[0xA8, 0x08], &[0]).map(|_| ())
    }
    fn frame(&mut self, io: &mut dyn Io, colors: &[Color]) -> Result<(), String> {
        for (i, run) in colors.chunks(9).enumerate() {
            let mut a = [0u8; 30];
            a[0] = (i * 9) as u8;
            a[1] = run.len() as u8;
            for (k, c) in run.iter().enumerate() {
                a[2 + k * 3..5 + k * 3].copy_from_slice(&hsv(*c));
            }
            send(io, &[0xA8, 0x0A], &a)?;
        }
        Ok(())
    }
}

/// DetectQMKKeychronControllers: two tries, 100 ms apart.
fn open(api: &HidApi, info: &Info, _: &mut Vec<String>) -> Vec<Box<dyn Backend>> {
    for attempt in 0..2 {
        if attempt != 0 {
            std::thread::sleep(std::time::Duration::from_millis(100));
        }
        let Ok(mut io) = opened(api, info) else {
            continue;
        };
        if let Some(at) = probe(io.as_mut(), info.pid) {
            let name = if info.product.is_empty() {
                NAME
            } else {
                &info.product
            };
            let dev = matrix(&info.device_id(FAMILY), name, &at);
            return vec![Box::new(Driver::new(io, dev, FAMILY, Keychron))];
        }
    }
    Vec::new()
}

